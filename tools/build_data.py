# ------------------------------------------------------------ output helpers

class Asm:
    def __init__(self, title):
        self.lines = ['; ' + '-' * 59,
                      '; ' + title,
                      '; GENERATED by tools/build_data.py - do not edit by hand',
                      '; ' + '-' * 59, '']

    def label(self, name):
        self.lines.append(name + ':')

    def const(self, name, value):
        self.lines.append('%s = %s' % (name, value))

    def bytes(self, data, per_line=16):
        data = list(data)
        for i in range(0, len(data), per_line):
            self.lines.append('    !byte ' + ', '.join('$%02x' % b for b in data[i:i + per_line]))

    def words(self, names):
        for i in range(0, len(names), 8):
            self.lines.append('    !word ' + ', '.join(names[i:i + 8]))

    def raw(self, line):
        self.lines.append(line)

    def save(self, path):
        with open(path, 'w') as f:
            f.write('\n'.join(self.lines) + '\n')


def rle_pack(data):
    """b < $80: b+1 literal bytes follow; b >= $80: (b - $7d) copies of the next byte."""
    out, i, n = [], 0, len(data)
    lit = []

    def flush():
        while lit:
            chunk = lit[:128]
            del lit[:128]
            out.append(len(chunk) - 1)
            out.extend(chunk)

    while i < n:
        j = i
        while j < n and data[j] == data[i] and j - i < 130:
            j += 1
        run = j - i
        if run >= 3:
            flush()
            out.append(0x7d + run)
            out.append(data[i])
            i = j
        else:
            lit.append(data[i])
            i += 1
    flush()
    return out


# ------------------------------------------------------------ text encoding

def scr(s):
    out = []
    for ch in s:
        o = ord(ch)
        if 'a' <= ch <= 'z':
            out.append(o - 96)
        elif 'A' <= ch <= 'Z':
            out.append(o)
        elif ch in '[]':
            out.append({'[': 27, ']': 29}[ch])
        elif 32 <= o <= 63:
            out.append(o)
        else:
            raise ValueError('no screen code for %r in %r' % (ch, s))
    return out


def wrap(s, width):
    return textwrap.wrap(s, width) or ['']


