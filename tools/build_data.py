def build_gfx():
    tiles, sprites, mp = load_tic(os.path.join(ASSETS, 'impostor.assets.lua'))
    asm = Asm('gen_gfx.asm - scenes, figures, images, art, arrows, clock')
    total = 0

    # ---- full scenes: a cell dictionary, then the packed cell indexes
    # (17 x 30) and colors (17 x 30) ----
    scenes = [('bedroom', render_map(tiles, mp, 0)),
              ('street', render_map(tiles, mp, 30)),
              ('office', render_map(tiles, mp, 60))]
    mm = lua_rle_arrays(os.path.join(ASSETS, 'screen.mysterious_man.lua'))
    ddr = lua_rle_arrays(os.path.join(ASSETS, 'window.minigame.ddr.lua'))
    scenes += [('mman', render_rle(*mm[0])), ('dayswitch', render_rle(*mm[1])),
               ('ddrbg', render_rle(*ddr[0]))]
    for name, cv in scenes:
        cells, colors = [], []
        for row in cells_of(cv):
            for px in row:
                data, ink, paper = opaque_cell(px)
                cells.append(tuple(data))
                colors.append((ink << 4) | paper)
        uniq = sorted(set(cells))
        assert len(uniq) <= 256, name
        index = [uniq.index(c) for c in cells]
        data = [len(uniq) & 0xff] + [b for c in uniq for b in c] + rle_pack(index + colors)
        asm.label('scn_' + name)
        asm.bytes(data)
        total += len(data)
        print('scene %-10s %5d bytes (%d cells)' % (name, len(data), len(uniq)))

    # ---- figures ----
    origins = {}
    for i, (name, parts, ycorr) in enumerate(FIGDEFS):
        cv, ox, oy = build_figure(sprites, parts)
        origins[name] = (ox, oy, ycorr)
        total += emit_figure(asm, name, cv)
        asm.const('FIG_' + name.upper(), i)
    cv, _, _ = build_figure(sprites, NORMAN, scale=4)
    total += emit_figure(asm, 'bignorman', cv)
    asm.const('FIG_BIGNORMAN', len(FIGDEFS))
    names = ['fig_' + n for n, _, _ in FIGDEFS] + ['fig_bignorman']
    asm.label('figlo')
    asm.raw('    !byte ' + ', '.join('<' + n for n in names))
    asm.label('fighi')
    asm.raw('    !byte ' + ', '.join('>' + n for n in names))
    asm.label('figycorr')
    asm.bytes([origins[n][2] for n, _, _ in FIGDEFS] + [0])

    # ---- fixed placements (scene-relative cells) ----
    fixed = {
        'POS_HOME_NORMAN': ('norman', 100, 80),
        'POS_OFFICE_NORMAN': ('norman', 13 * 8, 9 * 8),
        'POS_OFFICE_ECHO': ('norman', 15 * 8, 9 * 8),
        'POS_STREET_NORMAN': ('norman', 7 * 8, 3 * 8),
        'POS_STREET_NORMAN_FOOD': ('norman', 19 * 8, 3 * 8),
        'POS_SUMPHORE': ('sumphore', 9 * 8, 2 * 8),
        'POS_VENDOR': ('vendor', 19 * 8, 1 * 8),
        'POS_GUARD_HOME': ('guard', 22 * 8, 2 * 8),
        'POS_GUARD_OFFICE': ('guard', 22 * 8, 3 * 8),
        'POS_TOILET_NORMAN': ('norman', 180, 102),
        'POS_SLEEPING': ('sleeping', 120 - 30, 68 - 22),
    }
    for const, (fig, x, y) in fixed.items():
        ox, oy, _ = origins[fig]
        cx, cy = cell_of(x, y, ox, oy)
        asm.const(const + '_X', cx)
        asm.const(const + '_Y', cy)

    office_pos = [(6 * 8, 4 * 8), (10 * 8, 11 * 8 + 4), (12 * 8, 4 * 8), (15 * 8, 9 * 8),
                  (16 * 8, 4 * 8), (17 * 8, 8 * 8), (17 * 8, 11 * 8), (20 * 8, 4 * 8),
                  (23 * 8, 5 * 8), (22 * 8, 10 * 8 + 4), (27 * 8, 10 * 8 + 4), (-4 + 5 * 8, 9 * 8)]
    street_pos = [(x * 8, 11 * 8) for x in (5, 7, 9, 11, 13, 15, 18, 21, 24, 27)]
    for lbl, pos in (('office_pos', office_pos), ('street_pos', street_pos)):
        asm.label(lbl + 'x')
        asm.bytes([cell_of(x, y, -4, -4)[0] for x, y in pos])
        asm.label(lbl + 'y')
        asm.bytes([cell_of(x, y, -4, -4)[1] for x, y in pos])
    asm.const('NOFFICEPOS', len(office_pos))
    asm.const('NSTREETPOS', len(street_pos))

    # ---- ascii art ----
    arts = [('title', content.TITLE_ART, 'quad'), ('ttg', content.TTG_ART, 'full'),
            ('gameover', content.GAME_OVER_ART, 'full'), ('continued', content.CONTINUED_ART, 'full')]
    for name, art, mode in arts:
        w, h, cells = art_cells(art, mode)
        asm.label('art_' + name)
        asm.bytes([w, h] + [m for row in cells for m in row], per_line=w if w <= 40 else 16)
        total += 2 + w * h
        asm.const('ART_%s_W' % name.upper(), w)
        asm.const('ART_%s_H' % name.upper(), h)

    # ---- DDR arrows: hardware sprite shapes + 2x2 cell targets ----
    asm.label('arrow_cells')
    for d in ('left', 'down', 'up', 'right'):
        g = arrow_pixels(d)
        cells = []
        for cy in range(2):
            for cx in range(2):
                cells += [grid_byte(g, cx * 8, cy * 8 + y) for y in range(8)]
        asm.bytes(cells)
    asm.label('arrow_sprites')
    for d in ('left', 'down', 'up', 'right'):
        g = arrow_pixels(d)
        spr = []
        for y in range(21):
            if y < 16:
                spr += [grid_byte(g, 0, y), grid_byte(g, 8, y), 0]
            else:
                spr += [0, 0, 0]
        asm.bytes(spr + [0], per_line=21)

    # ---- the clock: 16 frames of 2x2 cells ----
    asm.label('clock_cells')
    for g in clock_frames():
        cells = []
        for cy in range(2):
            for cx in range(2):
                cells += [grid_byte(g, cx * 8, cy * 8 + y) for y in range(8)]
        asm.bytes(cells)

    asm.save(os.path.join(ROOT, 'gen_gfx.asm'))
    print('gfx total %d bytes' % total)


ACTIONS = {None: 0, 'coworker': 1, 'sumphore': 2, 'glitch': 3, 'pizza_end': 4,
           'sumphore_asc6': 5, 'sumphore_done': 6, 'echo_done': 7, 'eat_pizza': 8,
           'met_sumphore': 9, 'ism10': 10, 'bm10': 11, 'ism5': 12, 'wpm10': 13, 'drain': 14}

Q_WIDTH, Q_LINES = 34, 6
A_WIDTH, A_LINES = 36, 2
MM_WIDTH = 38


def text_block(asm, label, lines):
    asm.label(label)
    data = [len(lines)]
    for line in lines:
        data += scr(line) + [0]
    asm.bytes(data)
    return len(data)


def build_text():
    asm = Asm('gen_text.asm - discussions and the long texts')
    total = 0
    for name, code in ACTIONS.items():
        if name:
            asm.const('ACT_' + name.upper(), code)

    ids = [k for k in content.DISCUSSIONS if k not in content.MISSING]
    for i, did in enumerate(ids):
        asm.const('D_' + did.upper(), i)
    asm.const('NDISC', len(ids))
    asm.label('disclo')
    asm.raw('    !byte ' + ', '.join('<disc_' + d for d in ids))
    asm.label('dischi')
    asm.raw('    !byte ' + ', '.join('>disc_' + d for d in ids))
    for did in ids:
        onend, steps = content.DISCUSSIONS[did]
        asm.label('disc_' + did)
        asm.bytes([ACTIONS[onend], len(steps)])
        asm.words(['%s_s%d' % (did, i + 1) for i in range(len(steps))])
        total += 2 + 2 * len(steps)
        for si, (question, answers) in enumerate(steps):
            q = wrap(question, Q_WIDTH)
            assert len(q) <= Q_LINES, (did, question)
            sl = '%s_s%d' % (did, si + 1)
            asm.label(sl)
            asm.raw('    !word %s_q' % sl)
            asm.bytes([len(answers)])
            for ai, (label, nxt, act) in enumerate(answers):
                asm.raw('    !word %s_a%d' % (sl, ai + 1))
                asm.bytes([nxt or 0, ACTIONS[act]])
            total += 3 + 4 * len(answers)
            total += text_block(asm, sl + '_q', q)
            for ai, (label, nxt, act) in enumerate(answers):
                a = wrap(label, A_WIDTH)
                assert len(a) <= A_LINES, (did, label)
                total += text_block(asm, '%s_a%d' % (sl, ai + 1), a)

    def mm_lines(txt):
        out = []
        for line in txt.strip('\n').split('\n'):
            out += wrap(line.strip(), MM_WIDTH)
        return out

    total += text_block(asm, 'mmt_new', mm_lines(content.NEW_GAME_TEXT))
    for i, txt in enumerate(content.ASCENSION_TEXTS):
        total += text_block(asm, 'mmt_%d' % (i + 1), mm_lines(txt))
    asm.label('mmtlo')
    asm.raw('    !byte ' + ', '.join('<mmt_%d' % (i + 1) for i in range(9)))
    asm.label('mmthi')
    asm.raw('    !byte ' + ', '.join('>mmt_%d' % (i + 1) for i in range(9)))
    total += text_block(asm, 'brief_text', content.BRIEF_TEXT.split('\n'))
    asm.save(os.path.join(ROOT, 'gen_text.asm'))
    print('text total %d bytes' % total)


if __name__ == '__main__':
    build_gfx()
    build_text()
