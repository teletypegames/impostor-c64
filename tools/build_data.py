def build_figure(sprites, parts, scale=1):
    ox = min(p[1] for p in parts)
    oy = min(p[2] for p in parts)
    w = max(p[1] for p in parts) - ox + 8
    h = max(p[2] for p in parts) - oy + 8
    cv = Canvas(((w * scale + 7) // 8) * 8, ((h * scale + 7) // 8) * 8)
    for s, x, y, flip in parts:
        g = sprites.get(s - 256)
        if g:
            cv.blit(g, (x - ox) * scale, (y - oy) * scale, flip_y=flip, scale=scale)
    return cv, ox, oy


def emit_figure(asm, name, cv):
    w, h = cv.w // 8, cv.h // 8
    asm.label('fig_' + name)
    data = [w, h]
    for cy in range(h):
        for cx in range(w):
            c = sprite_cell(cell_pixels(cv, cx, cy))
            if c is None:
                data.append(0)
            elif c[0] == 'opaque':
                _, _, bits, ink, paper = c
                data += [1] + bits + [(ink << 4) | paper]
            else:
                _, mask, bits, c1, c2 = c
                data += [2] + mask + bits + [(c1 << 4) | c2]
    asm.bytes(data)
    return len(data)


def cell_of(x, y, ox, oy):
    return (x + ox + 4) // 8, (y + oy + 4) // 8


# ------------------------------------------------------------ DDR arrows

def arrow_pixels(direction):
    """The TIC draw_arrow shape (size 14) as a 16x16 bool grid."""
    size, half = 14, 7
    px, py = half, half
    steps = {'down': 0, 'right': 1, 'up': 2, 'left': 3}[direction]

    def rot(x, y):
        dx, dy = x - px, y - py
        for _ in range(steps % 4):
            dx, dy = dy, -dx
        return px + dx, py + dy

    a = rot(0, half)
    b = rot(half, size)
    c = rot(size, half)
    s1 = rot(half - 3, 0)
    s2 = rot(half + 3, half)
    grid = [[False] * 16 for _ in range(16)]

    def inside(x, y):
        def side(p, q, r):
            return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])
        d1, d2, d3 = side(a, b, (x, y)), side(b, c, (x, y)), side(c, a, (x, y))
        neg = d1 < 0 or d2 < 0 or d3 < 0
        pos = d1 > 0 or d2 > 0 or d3 > 0
        return not (neg and pos)

    for y in range(16):
        for x in range(16):
            if inside(x + 0.5, y + 0.5):
                grid[y][x] = True
    sx, sy = min(s1[0], s2[0]), min(s1[1], s2[1])
    sw, sh = abs(s2[0] - s1[0]), abs(s2[1] - s1[1])
    for x in range(sx, sx + sw):
        for y in (sy, sy + sh - 1):
            if 0 <= x < 16 and 0 <= y < 16:
                grid[y][x] = True
    for y in range(sy, sy + sh):
        for x in (sx, sx + sw - 1):
            if 0 <= x < 16 and 0 <= y < 16:
                grid[y][x] = True
    return grid


def grid_byte(grid, x0, y):
    v = 0
    for x in range(8):
        v = (v << 1) | (1 if grid[y][x0 + x] else 0)
    return v


# ------------------------------------------------------------ the clock

def clock_frames(n=16):
    frames = []
    for f in range(n):
        prog = (f + 1) / n
        grid = [[False] * 16 for _ in range(16)]
        for y in range(16):
            for x in range(16):
                dx, dy = x - 7.5, y - 7.5
                d = math.hypot(dx, dy)
                if 4.2 < d <= 7.6:
                    ang = (math.atan2(dy, dx) + math.pi / 2) % (2 * math.pi)
                    if ang / (2 * math.pi) <= prog:
                        grid[y][x] = True
                    elif (x + y) % 2 == 0:
                        grid[y][x] = True
        hand = -math.pi / 2 + prog * 2 * math.pi
        hx, hy = math.cos(hand), math.sin(hand)
        for t in range(0, 4):
            gx, gy = int(round(7.5 + hx * t)), int(round(7.5 + hy * t))
            grid[gy][gx] = True
        frames.append(grid)
    return frames


# ------------------------------------------------------------ ascii art

def art_cells(art, mode):
    lines = [l.replace('_', ' ') for l in art.strip('\n').split('\n')]
    width = max(len(l) for l in lines)
    lines = [l.ljust(width) for l in lines]
    if mode == 'full':
        return width, len(lines), [[15 if ch == '#' else 0 for ch in l] for l in lines]
    w, h = (width + 1) // 2, (len(lines) + 1) // 2
    out = []
    for cy in range(h):
        row = []
        for cx in range(w):
            m = 0
            for bit, (dx, dy) in ((8, (0, 0)), (4, (1, 0)), (2, (0, 1)), (1, (1, 1))):
                y, x = cy * 2 + dy, cx * 2 + dx
                if y < len(lines) and x < width and lines[y][x] == '#':
                    m |= bit
            row.append(m)
        out.append(row)
    return w, h, out


